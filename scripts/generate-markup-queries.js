#!/usr/bin/env node
/**
 * Generate markup/queries/*.scm from queries/*.scm.
 *
 * Both grammars are built from common/define-grammar.js, and a template's
 * tree is the script tree plus `text_statement` nodes and the tag tokens (see
 * the comment at the top of that file). Every code-grammar query therefore
 * applies to templates unchanged, so each markup query file is its
 * `queries/` counterpart plus, for highlights only, the few template-only
 * patterns below. The one rewrite is the root node: `(program)` becomes
 * `(markup)`, the template grammar's start rule.
 *
 * Editors that understand `; inherits: ucode` (Neovim, Helix) could load the
 * code queries themselves, but tree-sitter.json consumers and the CLI need a
 * self-contained file per grammar, so the files are concatenated here instead.
 *
 * Run via `npm run build`.
 */

'use strict';

const fs   = require('fs');
const path = require('path');

const root   = path.resolve(__dirname, '..');
const srcDir = path.join(root, 'queries');
const dstDir = path.join(root, 'markup', 'queries');

const HIGHLIGHTS_TEMPLATE_EXTRA = `
; ── Template-only nodes ─────────────────────────────────────────────────────

[
  (statement_tag_open)
  (statement_tag_trim_open)
  (statement_tag_lstrip_open)
  (statement_tag_close)
  (statement_tag_trim_close)
  (expression_tag_open)
  (expression_tag_trim_open)
  (expression_tag_close)
  (expression_tag_trim_close)
] @punctuation.special

(comment_tag) @comment
`;

// [prepend, append] per file.
const EXTRAS = {
  'highlights.scm': ['', HIGHLIGHTS_TEMPLATE_EXTRA],
};

const QUERIES = [
  'folds.scm',
  'highlights.scm',
  'indents.scm',
  'injections.scm',
  'locals.scm',
  'tags.scm',
  'textobjects.scm',
];

fs.mkdirSync(dstDir, { recursive: true });

for (const file of QUERIES) {
  const header =
    `; GENERATED by scripts/generate-markup-queries.js from queries/${file}\n` +
    '; — do not edit by hand.\n\n';
  const base  = fs.readFileSync(path.join(srcDir, file), 'utf8')
    .replace(/\(program\)/g, '(markup)');
  const [before, after] = EXTRAS[file] || ['', ''];
  fs.writeFileSync(path.join(dstDir, file), header + before + base + after, 'utf8');
  console.log(`Wrote markup/queries/${file}`);
}
