#!/usr/bin/env node
/**
 * Generate ucode_markup/queries/*.scm from ucode/queries/*.scm.
 *
 * A template tree is the script tree plus text_statement nodes and tag tokens,
 * so each markup query is its ucode counterpart with `(program)` renamed to
 * `(markup)`, plus the template-only patterns below. Files are concatenated
 * rather than using `; inherits:` because the CLI and tree-sitter.json
 * consumers need self-contained queries.
 *
 * Run via `npm run build`.
 */

'use strict';

const fs   = require('fs');
const path = require('path');

const root   = path.resolve(__dirname, '..');
const srcDir = path.join(root, 'ucode', 'queries');
const dstDir = path.join(root, 'ucode_markup', 'queries');

const HIGHLIGHTS_TEMPLATE_EXTRA = `
; Template-only nodes

[
  (statement_tag_open)
  (statement_tag_trim_open)
  (statement_tag_lstrip_open)
  (statement_tag_close)
  (statement_tag_trim_close)
  (expression_tag_open)
  (expression_tag_trim_open)
  (expression_tag_close)
  (expression_tag_trim_close)
] @punctuation.special

(comment_tag) @comment
`;

// A doc comment in the tag before a declaration is separated from it by a
// whitespace-only text_statement, so the base `(comment)* @doc .` patterns
// miss it. `+` avoids tagging doc-less declarations twice. Prepended:
// tree-sitter-tags keeps the lowest pattern index per name.
const TAGS_TEMPLATE_EXTRA = String.raw`
; Template-only: doc comment in the previous tag

(
  [(comment) (doc_comment)]+ @doc
  .
  (text_statement) @_gap
  .
  (function_declaration
    name: (identifier) @name) @definition.function
  (#match? @_gap "^-?%\\}\\s*\\{%[-+]?$")
  (#strip! @doc "^[\\s\\*/]+|[\\s\\*/]+$")
  (#select-adjacent! @doc @definition.function)
)

(
  [(comment) (doc_comment)]+ @doc
  .
  (text_statement) @_gap
  .
  (lexical_declaration
    (variable_declarator
      name: (identifier) @name
      value: [(function_expression) (arrow_function)])) @definition.function
  (#match? @_gap "^-?%\\}\\s*\\{%[-+]?$")
  (#strip! @doc "^[\\s\\*/]+|[\\s\\*/]+$")
  (#select-adjacent! @doc @definition.function)
)
`;

// `{% } %}`, `{% endfor %}`, `{% else %}`: the leading `{%` closes the body's
// last text_statement, so dedent it to the block's level.
const INDENTS_TEMPLATE_EXTRA = `
; Template-only: a tag that ends a body

(statement_block
  (text_statement
    [
      (statement_tag_open)
      (statement_tag_trim_open)
      (statement_tag_lstrip_open)
    ] @indent.branch .)
  .
  "}")

(statement_list
  (text_statement
    [
      (statement_tag_open)
      (statement_tag_trim_open)
      (statement_tag_lstrip_open)
    ] @indent.branch .) .)
`;

// [prepend, append] per file.
const EXTRAS = {
  'highlights.scm': ['', HIGHLIGHTS_TEMPLATE_EXTRA],
  'indents.scm': ['', INDENTS_TEMPLATE_EXTRA],
  'tags.scm': [TAGS_TEMPLATE_EXTRA.trimStart() + '\n', ''],
};

const QUERIES = [
  'folds.scm',
  'highlights.scm',
  'indents.scm',
  'injections.scm',
  'locals.scm',
  'tags.scm',
  'textobjects.scm',
];

fs.mkdirSync(dstDir, { recursive: true });

for (const file of QUERIES) {
  const header =
    `; GENERATED by scripts/generate-markup-queries.js from ucode/queries/${file}\n` +
    '; — do not edit by hand.\n\n';
  const base  = fs.readFileSync(path.join(srcDir, file), 'utf8')
    .replace(/\(program\)/g, '(markup)');
  const [before, after] = EXTRAS[file] || ['', ''];
  fs.writeFileSync(path.join(dstDir, file), header + before + base + after, 'utf8');
  console.log(`Wrote ucode_markup/queries/${file}`);
}
