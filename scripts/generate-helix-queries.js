#!/usr/bin/env node
/**
 * Generate editors/helix/queries/<language>/*.scm — query files for Helix.
 *
 * The repo's queries use nvim-treesitter capture names. Helix reads the same
 * query files but has its own conventions (https://docs.helix-editor.com):
 *
 *   highlights   different scope names (variable.other.member,
 *                keyword.control.conditional, constant.numeric, …) — derived
 *                here by renaming captures (HIGHLIGHT_NAMES); @spell dropped.
 *   locals       `@local.definition.<scope>`, where the suffix is the highlight
 *                Helix gives references to that definition — derived from
 *                each pattern's `(#set! local.kind …)` (LOCAL_KINDS); the
 *                repo's own file uses plain @local.definition, which is all
 *                tree-sitter-highlight and tree-sitter-tags accept.
 *   injections,  same conventions — copied unchanged.
 *   tags
 *   textobjects  `.inside` / `.around`, and a different set of objects
 *   indents      a different model (@indent / @outdent / @extend, scope
 *                settings) — neither translates mechanically, so both are
 *                written below for Helix, adapted from Helix's own ECMAScript
 *                and C queries to this grammar's node names. Indents are
 *                checked in a real Helix by scripts/check-helix-indents.sh.
 *   folds        not used by Helix.
 *
 * Helix finds queries by LANGUAGE name (runtime/queries/<name>/), so the
 * output directories are the language names the README's languages.toml uses:
 * ucode, ucode-markup, ucdocs.
 *
 * Run via `npm run build` (after generate-markup-queries.js).
 */

'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.dirname(__dirname);
const OUT = path.join(ROOT, 'editors', 'helix', 'queries');

const SOURCES = {
  ucode: 'ucode/queries',
  'ucode-markup': 'ucode_markup/queries',
  ucdocs: 'ucdocs/queries',
};

// nvim-treesitter capture → Helix scope (themes.md "Scopes"). A name not listed
// here and not already a Helix scope makes the generator fail — see
// assertKnown() — so a new capture can't silently go unstyled in Helix.
const HIGHLIGHT_NAMES = {
  'variable.member': 'variable.other.member',
  boolean: 'constant.builtin.boolean',
  number: 'constant.numeric',
  'string.escape': 'constant.character.escape',
  'function.call': 'function',
  'function.method.call': 'function.method',
  'keyword.conditional': 'keyword.control.conditional',
  'keyword.repeat': 'keyword.control.repeat',
  'keyword.return': 'keyword.control.return',
  'keyword.exception': 'keyword.control.exception',
  'keyword.import': 'keyword.control.import',
  module: 'namespace',
  'comment.documentation': 'comment.block.documentation',
  'markup.link': 'markup.link.url',
};

// Helix highlight scopes this file may emit (a subset of themes.md's list).
const HELIX_SCOPES = new Set([
  'comment', 'comment.block.documentation', 'constant', 'constant.builtin', 'constant.builtin.boolean',
  'constant.character.escape', 'constant.numeric', 'function', 'function.builtin',
  'function.method',
  'keyword', 'keyword.control.conditional', 'keyword.control.exception',
  'keyword.control.import', 'keyword.control.repeat', 'keyword.control.return',
  'keyword.directive', 'keyword.function', 'keyword.operator', 'keyword.storage',
  'markup.link.url',
  'namespace', 'operator', 'punctuation.bracket', 'punctuation.delimiter',
  'punctuation.special', 'string', 'string.regexp', 'type', 'type.builtin',
  'type.parameter', 'variable', 'variable.builtin', 'variable.other.member',
  'variable.parameter',
]);

const LOCAL_KINDS = {
  var: 'local.definition.variable',
  parameter: 'local.definition.variable.parameter',
  function: 'local.definition.function',
  import: 'local.definition.variable',
};

function assertKnown(file, name, known) {
  if (!known.has(name)) {
    console.error(`${file}: capture @${name} has no Helix equivalent — add it to the mapping in ${path.basename(__filename)}`);
    process.exit(1);
  }
}

function header(from) {
  return `; GENERATED by scripts/generate-helix-queries.js${from ? ` from ${from}` : ''}\n; — do not edit by hand.\n\n`;
}

// Apply `fn` to every capture name in a query, leaving "strings" (e.g. the
// token "@param") and ; comments untouched. `fn` returns the new name, or null
// to drop the capture.
function mapCaptures(src, fn) {
  let out = '';
  for (let i = 0; i < src.length;) {
    const c = src[i];
    if (c === '"') {                                   // string literal
      let j = i + 1;
      while (j < src.length && src[j] !== '"') j += src[j] === '\\' ? 2 : 1;
      out += src.slice(i, j + 1); i = j + 1;
    } else if (c === ';') {                            // comment to end of line
      const j = src.indexOf('\n', i);
      const end = j < 0 ? src.length : j;
      out += src.slice(i, end); i = end;
    } else if (c === '@') {
      const m = /^@([\w.]+)/.exec(src.slice(i));
      const name = fn(m[1]);
      if (name === null) out = out.replace(/[ \t]*$/, '');
      else out += `@${name}`;
      i += m[0].length;
    } else {
      out += c; i++;
    }
  }
  return out;
}

function highlights(src, file) {
  return mapCaptures(src, (name) => {
    if (name.startsWith('_')) return name;               // predicate-only captures
    if (name === 'spell' || name === 'nospell') return null;
    const helix = HIGHLIGHT_NAMES[name] || name;
    assertKnown(file, helix, HELIX_SCOPES);
    return helix;
  });
}

// Split a query into top-level patterns (balanced parentheses), keeping the
// text between them (comments, blank lines) as separate chunks. Comments and
// strings are skipped so a parenthesis inside them does not count.
function topLevelChunks(src) {
  const chunks = [];
  let depth = 0, start = 0;
  for (let i = 0; i < src.length; i++) {
    const c = src[i];
    if (c === ';') { while (i < src.length && src[i] !== '\n') i++; continue; }
    if (c === '"') { for (i++; i < src.length && src[i] !== '"'; i++) if (src[i] === '\\') i++; continue; }
    if (c === '(') { if (depth++ === 0) { chunks.push(src.slice(start, i)); start = i; } }
    else if (c === ')' && --depth === 0) { chunks.push(src.slice(start, i + 1)); start = i + 1; }
  }
  chunks.push(src.slice(start));
  return chunks;
}

function locals(src) {
  return topLevelChunks(src).map((chunk) => {
    const kind = /\(#set! local\.kind (\w+)\)/.exec(chunk);
    if (!kind) return chunk;
    const helix = LOCAL_KINDS[kind[1]];
    if (!helix) {
      console.error(`locals.scm: local.kind ${kind[1]} has no Helix equivalent — add it to LOCAL_KINDS in ${path.basename(__filename)}`);
      process.exit(1);
    }
    return chunk
      .replace(/\n?[ \t]*\(#set! (local\.kind|definition\.[\w.]+) \w+\)/g, '')   // metadata Helix does not use
      .replace(/@local\.definition\b(?!\.)/g, `@${helix}`);
  }).join('');
}

const TEXTOBJECTS = `; Functions
(function_declaration
  body: (_) @function.inside) @function.around

(function_expression
  body: (_) @function.inside) @function.around

(arrow_function
  body: (_) @function.inside) @function.around

; Parameters and arguments
(formal_parameters
  ((_) @parameter.inside . ","? @parameter.around) @parameter.around)

(arguments
  ((_) @parameter.inside . ","? @parameter.around) @parameter.around)

; Comments
[(comment) (doc_comment)] @comment.inside

[(comment) (doc_comment)]+ @comment.around

; Array elements and object entries
(array
  (_) @entry.around)

(pair
  (_) @entry.inside) @entry.around
`;

// Uses only indent features of the current Helix release (25.07.1): its own
// queries use `#not-kind-eq?` and the "all"/"tail" scopes. Newer idioms on
// Helix's master branch (`#set! "scope" "header"`, `@opaque`) make 25.07.1
// reject the WHOLE file ("Failed to compile indents.scm query"), silently.
// Check changes with scripts/check-helix-indents.sh (see CONTRIBUTING).
const INDENTS = `[
  (array)
  (object)
  (arguments)
  (formal_parameters)
  (statement_block)
  (switch_body)
  (named_imports)
  (export_clause)
  (binary_expression)
  (return_statement)
  (template_substitution)
] @indent

[
  (switch_case)
  (switch_default)
] @indent @extend

[
  "}"
  "]"
  ")"
] @outdent

; Alt-syntax bodies (\`if (c): … endif\`, and in templates {% if (c): %}…{% endif %}):
; the body indents, the end keyword and each elif/else line outdent.
[
  (if_alt_statement)
  (for_alt_statement)
  (for_in_alt_statement)
  (while_alt_statement)
] @indent

(function_declaration "endfunction") @indent

[
  "endif"
  "endfor"
  "endwhile"
  "endfunction"
] @outdent

(elif_clause "elif" @outdent)
(else_alt_clause "else" @outdent)

; Single-statement bodies without braces. Helix starts from the smallest node
; that CONTAINS the cursor, and a node ending exactly there does not, so after
; \`if (c)\` + Enter the body node is not on the path and the C-style patterns
; below never fire for a new line. Indent the whole statement's tail instead
; (only without an \`else\`, whose line must not indent) …
(if_statement
  consequence: (_) @_body
  !alternative
  (#not-kind-eq? @_body "statement_block")) @indent
(else_clause
  (_) @_body
  (#not-kind-eq? @_body "statement_block")
  (#not-kind-eq? @_body "if_statement")) @indent
(while_statement
  body: (_) @_body
  (#not-kind-eq? @_body "statement_block")) @indent
(for_statement
  body: (_) @_body
  (#not-kind-eq? @_body "statement_block")) @indent
(for_in_statement
  body: (_) @_body
  (#not-kind-eq? @_body "statement_block")) @indent

; … and at the end of the file, where the not-yet-typed body is a statement
; the parser made up from a MISSING token (an identifier or a \`;\`), extend
; the statement over the cursor so its indent applies (Helix's \`@extend\`).
(if_statement consequence: (_ . (MISSING) .)) @extend
(else_clause (_ . (MISSING) .)) @extend
(while_statement body: (_ . (MISSING) .)) @extend
(for_statement body: (_ . (MISSING) .)) @extend
(for_in_statement body: (_ . (MISSING) .)) @extend
; A dangling \`else\` at the end of the file gets no inserted body: it is an
; ERROR holding just the keyword.
(ERROR . "else" .) @indent @extend

; Re-indenting an existing body line (as in Helix's C indents).
(if_statement
  consequence: (_) @indent
  (#not-kind-eq? @indent "statement_block")
  (#set! "scope" "all"))
(else_clause
  (_) @indent
  (#not-kind-eq? @indent "statement_block")
  (#not-kind-eq? @indent "if_statement")
  (#set! "scope" "all"))
(while_statement
  body: (_) @indent
  (#not-kind-eq? @indent "statement_block")
  (#set! "scope" "all"))
(for_statement
  body: (_) @indent
  (#not-kind-eq? @indent "statement_block")
  (#set! "scope" "all"))
(for_in_statement
  body: (_) @indent
  (#not-kind-eq? @indent "statement_block")
  (#set! "scope" "all"))
`;

const written = [];
function write(lang, file, content) {
  const dir = path.join(OUT, lang);
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(path.join(dir, file), content, 'utf8');
  written.push(`${lang}/${file}`);
}

for (const [lang, srcDir] of Object.entries(SOURCES)) {
  // The markup sources are generated too; drop their own GENERATED header so
  // the output carries only this script's.
  const read = (f) => fs.readFileSync(path.join(ROOT, srcDir, f), 'utf8')
    .replace(/^; GENERATED by [^\n]*\n; — do not edit by hand\.\n\n/, '');
  const has = (f) => fs.existsSync(path.join(ROOT, srcDir, f));
  const from = (f) => `${srcDir}/${f}`;

  write(lang, 'highlights.scm', header(from('highlights.scm')) + highlights(read('highlights.scm'), from('highlights.scm')));
  for (const f of ['injections.scm', 'tags.scm']) {
    if (has(f)) write(lang, f, header(from(f)) + read(f));
  }
  if (has('locals.scm')) write(lang, 'locals.scm', header(from('locals.scm')) + locals(read('locals.scm')));
  if (lang !== 'ucdocs') {
    write(lang, 'textobjects.scm', header() + TEXTOBJECTS);
    write(lang, 'indents.scm', header() + INDENTS);
  }
}

console.log(`Wrote ${written.length} files under editors/helix/queries/`);
